def route_km(stops: tuple[str, ...]) -> float:
    return sum(great_circle_km(*S[a], *S[b]) for a, b in zip(stops, stops[1:], strict=False))


def catalog() -> dict:
    """화면에 넘겨줄 기차 노선 목록 (짧은 순)."""
    routes = []
    for r in sorted(ROUTES, key=lambda r: r.minutes):
        routes.append(
            {
                "id": r.id,
                "name": r.name,
                "line": r.line,
                "minutes": r.minutes,
                "distance_km": round(route_km(r.stops)),
                "stops": list(r.stops),
                # 지도에 그릴 선: [경도, 위도]
                "coords": [[S[s][1], S[s][0]] for s in r.stops],
            }
        )
    return {"origin": ORIGIN, "routes": routes}
